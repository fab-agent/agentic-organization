//! TR / EN strings. Language from `FAB_LANG`, then `LANG`; default English.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Tr,
}

pub fn detect() -> Lang {
    let v = std::env::var("FAB_LANG")
        .or_else(|_| std::env::var("LANG"))
        .unwrap_or_default()
        .to_lowercase();
    if v.starts_with("tr") {
        Lang::Tr
    } else {
        Lang::En
    }
}

